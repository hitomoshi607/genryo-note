export interface Help {
  title: string;
  body: ReactNode;
}

const Kv = ({ rows, wide }: { rows: [ReactNode, ReactNode][]; wide?: boolean }) => (
  <dl className={`kv${wide ? ' wide' : ''}`}>
    {rows.map(([k, v], i) => (
      <div key={i}>
        <dt>{k}</dt>
        <dd>{v}</dd>
      </div>
    ))}
  </dl>
);

const Box = ({ title, children }: { title?: string; children: ReactNode }) => (
  <div className="box">
    {title && <b>{title}</b>}
    {title && <br />}
    {children}
  </div>
);

